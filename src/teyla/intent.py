"""`teyla intent` — the owner's own long prompts, kept word for word, one file per product.

    ~/.teyla/intent/<product>.md      append-only, 0600, in a 0700 directory
    ~/.teyla/intent/.index.json       hashes, dates, product, session, length (dedupe only)

Why: the owner describes a goal in a long prompt. An agent turned it into a plan, a later
session worked from the plan, and the detail was gone: a summary had replaced the source. So
nothing here summarises. A prompt of `intent.min_chars` (default 400) or more is stored as typed,
after `corrections.scrub` has replaced secrets, and a planning session is pointed at the file.

    teyla intent                         one line per product: entries, latest date
    teyla intent <product> [--days N] [--grep TEXT] [--json]   one line per entry
    teyla intent path <product>          the file, for `cat "$(teyla intent path x)"`
    teyla intent cover <plan.md> [--product P] [--since DATE] [--last N] [--model] [--json]
                                         which of the owner's sentences a plan neither serves nor sets aside
    teyla intent backfill [--days 30] [--dry]   the same capture from Claude Code and Codex transcripts
    teyla intent clean [--dry]           drop stored entries the owner did not type, under today's rules
    teyla intent audit <product> [--open] [--json]   which requests were delivered, what is still owed
    teyla intent mark <id> <status> [--quote TEXT] [--evidence E] [--note N]   record one (intent_status.py)
    teyla intent load <product> <file.json> [--dry]  many records at once, all or nothing
    teyla intent rebuild <product> [--days N] [--dry]   make a product's file again from the transcripts
    teyla intent capture                 what plugin/hooks/capture-intent.sh runs (JSON on stdin)

An entry:

    ## 2026-10-16 18:40 · claude · session 1a2b3c4d
    <the prompt, verbatim, secrets scrubbed>

Product is the repo name of the prompt's cwd. A worktree (`<repo>/.claude/worktrees/<x>`,
`~/.worktrees/<repo>/<branch>`, or any checkout whose `.git` file points at a main checkout)
maps to its repo; a cwd outside any repo goes to `general`.

What is not stored: prompts a script or another agent wrote (`claude -p`, `codex exec`, `grok -p`,
Codex review briefs, subagent briefs, injected AGENTS.md text), harness-injected turns (system
reminders, task notifications, a subagent's report handed back, slash-command expansions) and images. Text pasted into a prompt
arrives inline and cannot be told from typing; a prompt over MAX_CHARS keeps its first MAX_CHARS
characters and says how many were left out. A line of a prompt that looks like an entry
header gets a backslash in front, so the file stays parseable.

`clean` is the repair for entries stored before a rule existed: it re-checks every entry against the
current rules, copies each file it changes to `<file>.bak-<UTC time>` (0600) and rewrites file and
index under the same lock. Entries it keeps stay byte for byte as they were.

Writes are safe under concurrent hooks: one flock around "read index, append, write index",
the file written with O_APPEND and fsynced, the index replaced atomically. A hook that cannot
get the lock within a second skips the capture; `teyla intent backfill` finds it again.
Everything the hook runs is stdlib.
"""
from __future__ import annotations

import contextlib
import datetime as _dt
import hashlib
import json
import os
import pathlib
import re
import sys
import time

from . import corrections
from .adapters import HANDBACK_MARKER

try:  # POSIX only; without it the lock is skipped and dedupe is best effort
    import fcntl
except ImportError:  # pragma: no cover
    fcntl = None

MIN_CHARS = 400
MAX_CHARS = 50_000      # a longer prompt keeps its first MAX_CHARS characters; also the length the dedupe key covers
INDEX_VERSION = 2       # 1 hashed whole prompts with every line break collapsed; an older index is rebuilt
LOCK_WAIT_S = 1.0
INDEX_NAME = ".index.json"
LOCK_NAME = ".lock"

HEADER_RE = re.compile(r"^## (\d{4}-\d\d-\d\d \d\d:\d\d) · (\S+) · session (\S*)$")
_WORKTREE_RES = (
    re.compile(r"^(?P<root>.+?)/\.claude/worktrees(?:/|$)"),   # <repo>/.claude/worktrees/<x>
    re.compile(r"/\.worktrees/(?P<name>[^/]+)(?:/|$)"),        # ~/.worktrees/<repo>/<branch>
)

# Prompts that look typed but were written by a harness, a script or another agent. Both the live hook
# and the backfill use it.
_AUTOMATED_PREFIXES = (
    "# AGENTS.md instructions",
    "<INSTRUCTIONS>",
    "Base directory for this skill:",
    "<scheduled-task",
    "<artifact-content",
    "<bash-input>",
    "<bash-stdout>",
    "Caveat: The messages below were generated by the user while running local commands",
    "Codex could not read",
    "IMPORTANT: Do NOT read",
    "Background (from the session that started this one)",   # a brief one agent session wrote for another
    "You are reviewing a pull request diff",                 # codex-review / claude-review prompts
    "<task-notification",
    "<side-sessions-event",
    "<ci-monitor-event",
    "<agent-message",                                        # a subagent's report, filed by the Claude desktop app as a user turn
    "<cross-session-message",                                # one agent session messaging another; the live hook sees it as a prompt
    "Task (from the session",                                # the brief a side session is started with
    "<realtime_delegation",                                  # a voice agent handing work to Codex
    "<heartbeat",                                            # a Codex automation's scheduled run
    "This is an app-generated",                              # a request the Codex app writes itself
)
_AUTOMATED_HEAD_RE = re.compile(r"One-pass code review")
_IMAGE_TAG_RE = re.compile(r"</?image\b[^>]*>")
# Codex wraps a prompt that comes with files or a browser page: the files and page first, then
# "## My request" and what the person typed. Only that last part is theirs.
_CODEX_ENVELOPE_HEADS = ("# Files mentioned by the user", "<in-app-browser-context")
_MY_REQUEST_RE = re.compile(r"^## My request[ \t]*$", re.M)
_BROWSER_CTX_RE = re.compile(r"\A\s*<in-app-browser-context\b[^>]*>.*?</in-app-browser-context>\s*", re.S)
# Codex files the answer to a question it asked (`request_user_input`) as a user turn: JSON with
# the question and the option picked or typed.
_QUESTION_REPLY_RE = re.compile(r"\A\s*<send_user_message_question_reply>(.*)</send_user_message_question_reply>\s*\Z", re.S)
ASKED, ANSWERED = "Asked: ", "Answered: "


# --- where --------------------------------------------------------------------------------

def intent_dir() -> pathlib.Path:
    return corrections.teyla_home() / "intent"


def _clean_name(name: str) -> str:
    name = re.sub(r"[^A-Za-z0-9._-]+", "-", name or "").strip("-.")
    return name or "misc"


def product_for(cwd) -> str:
    """The product a prompt typed in `cwd` belongs to. Pure filesystem and path matching, no
    `git` subprocess (the hook runs on every prompt, and /usr/bin/git on a Mac without the
    developer tools pops a dialog). The path rules come first so a worktree that has been
    deleted since still maps to its repo."""
    try:
        p = pathlib.Path(cwd).expanduser().resolve()
    except (OSError, RuntimeError, TypeError, ValueError):
        return "misc"
    s = p.as_posix()
    m = _WORKTREE_RES[0].match(s)
    if m:
        return _clean_name(pathlib.PurePosixPath(m.group("root")).name)
    m = _WORKTREE_RES[1].search(s)
    if m:
        return _clean_name(m.group("name"))
    root, _ = corrections.find_repo(p)
    # Outside any repo (a parent folder like ~/repos, a download folder, a path that is gone):
    # one shared file, not a product named after whatever directory the session sat in.
    return _clean_name(root.name) if root else "general"


# --- what counts --------------------------------------------------------------------------

def automated(text: str) -> bool:
    """A prompt the owner did not type: an injected AGENTS.md, a review brief, a scheduled task,
    a skill's expansion, a subagent's report handed back."""
    t = (text or "").lstrip()
    return (t.startswith(_AUTOMATED_PREFIXES) or bool(_AUTOMATED_HEAD_RE.search(t[:300]))
            or t.startswith(HANDBACK_MARKER))


def answer_text(pairs) -> str | None:
    """A button answer, kept with the question it answered: an `Asked:` line and an `Answered:`
    line per pair. A short "Yes, build it" means nothing without its question."""
    lines = []
    for q, a in pairs:
        a = str(a or "").strip()
        if not a:
            continue
        q = " ".join(str(q or "").split())
        lines += ([ASKED + q] if q else []) + [ANSWERED + a]
    return "\n".join(lines) or None


def _unwrap(t: str) -> str:
    """The owner's part of a prompt a harness wrapped: a Codex question reply becomes its
    question and answer; a Codex files-or-page envelope becomes the text after "## My request"."""
    m = _QUESTION_REPLY_RE.match(t)
    if m:
        try:
            items = json.loads(m.group(1))
        except ValueError:
            return ""
        items = items if isinstance(items, list) else [items]
        return answer_text((i.get("question"), i.get("answer")) for i in items if isinstance(i, dict)) or ""
    if t.lstrip().startswith(_CODEX_ENVELOPE_HEADS):
        m = _MY_REQUEST_RE.search(t)
        if m:
            return t[m.end():].strip()
        return _BROWSER_CTX_RE.sub("", t, count=1).strip()
    return t


def typed(text: str | None) -> str | None:
    """What the owner typed in a user turn, or None: nothing left after the harness's own
    injections, an automated prompt, a retry."""
    from .adapters import human_text
    t = _unwrap(_IMAGE_TAG_RE.sub("", text or "").strip())
    t = human_text(t) if t else None
    if not t or automated(t):
        return None
    return t


def long_enough(text: str, min_chars: int) -> bool:
    """A prompt is kept from `min_chars` on; an answer to a question is kept whatever its length,
    because it comes with the question."""
    return len(text) >= min_chars or text.startswith((ASKED, ANSWERED))


def settings(cfg: dict | None = None) -> tuple[bool, int]:
    """(enabled, min_chars) from `[intent]`; a broken config means the defaults."""
    try:
        if cfg is None:
            from . import config
            cfg = config.load(corrections.teyla_home() / "config.toml")
        sec = (cfg or {}).get("intent") or {}
        enabled = sec.get("enabled", True)
        enabled = enabled if isinstance(enabled, bool) else str(enabled).strip().lower() not in ("0", "false", "no", "off")
        n = int(sec.get("min_chars", MIN_CHARS))
        return enabled, max(1, n)
    except Exception:  # noqa: BLE001 — a broken config must not stop a capture
        return True, MIN_CHARS


_CUT_RE = re.compile(r"\n\[(\d+) more characters not kept\]$")


def normalise(text: str) -> str:
    """The dedupe form: spaces within a line collapse, line ends and the blank lines around the
    text are ignored, but the line breaks stay. Two prompts that differ only in their layout are
    two prompts."""
    lines = (text or "").replace("\r\n", "\n").replace("\r", "\n").split("\n")
    return "\n".join(" ".join(l.split()) for l in lines).strip("\n")


def digest(text: str) -> str:
    """The dedupe key. It covers the first MAX_CHARS characters only, which is all an entry keeps,
    so a cut entry read back from the file has the key its full text had when it was written."""
    return hashlib.sha256(normalise(text[:MAX_CHARS]).encode("utf-8", "surrogatepass")).hexdigest()[:16]


def kept_text(text: str) -> tuple[str, int]:
    """(the prompt as kept, characters left out) for an entry's text: the closing
    `[N more characters not kept]` line of a cut entry is not part of the owner's words."""
    m = _CUT_RE.search(text or "")
    return (text[:m.start()], int(m.group(1))) if m else (text or "", 0)


# --- the store ----------------------------------------------------------------------------

def _escape(body: str) -> str:
    """A body line that would read as an entry header gets a backslash."""
    return "\n".join("\\" + l if HEADER_RE.match(l) else l for l in body.split("\n"))


def _unescape(body: str) -> str:
    return "\n".join(l[1:] if l.startswith("\\") and HEADER_RE.match(l[1:]) else l for l in body.split("\n"))


def parse(text: str) -> list[dict]:
    """The entries of one product file: {date, harness, session, text}."""
    out, cur = [], None
    for line in text.split("\n"):
        m = HEADER_RE.match(line)
        if m:
            cur = {"date": m.group(1), "harness": m.group(2), "session": m.group(3), "lines": []}
            out.append(cur)
        elif cur is not None:
            cur["lines"].append(line)
    for e in out:
        e["text"] = _unescape("\n".join(e.pop("lines")).strip("\n"))
    return out


class Store:
    """The intent directory, locked. `with Store() as st: st.add(...)`; the index is written
    once, on exit."""

    def __init__(self, wait_s: float = LOCK_WAIT_S, dry: bool = False):
        self.dir = intent_dir()
        self.wait_s = wait_s
        self.dry = dry  # read-only: no directory made, no lock, nothing written
        self._fd = None
        self._dirty = False
        self._planned: set[str] = set()
        self.index: dict = {}

    def __enter__(self) -> "Store":
        if self.dry:
            self.index = self._load_index()
            return self
        from . import config
        config.private_dir(corrections.teyla_home())
        config.private_dir(self.dir)
        if fcntl is not None:
            self._fd = os.open(self.dir / LOCK_NAME, os.O_RDWR | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0), 0o600)
            deadline = time.monotonic() + self.wait_s
            while True:
                try:
                    fcntl.flock(self._fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                    break
                except OSError:
                    if time.monotonic() >= deadline:
                        os.close(self._fd)
                        self._fd = None
                        raise TimeoutError("intent store is locked")
                    time.sleep(0.02)
        try:
            self.index = self._load_index()
        except BaseException:
            self._release()
            raise
        return self

    def __exit__(self, *exc) -> None:
        try:
            if self._dirty and not self.dry:
                self._write_index()  # entries already appended must stay deduped, even on an error
        finally:
            self._release()

    def _release(self) -> None:
        if self._fd is not None:
            try:
                fcntl.flock(self._fd, fcntl.LOCK_UN)
            finally:
                os.close(self._fd)
                self._fd = None

    # index ---------------------------------------------------------------------------------
    def _load_index(self) -> dict:
        p = self.dir / INDEX_NAME
        try:
            data = json.loads(p.read_text())
            seen = data["seen"]
            if isinstance(seen, dict) and data.get("version") == INDEX_VERSION:
                return seen
        except FileNotFoundError:
            if not any(self.dir.glob("*.md")):
                return {}
        except (OSError, ValueError, KeyError, TypeError):
            pass
        self._dirty = True
        return self._rebuild()

    def _rebuild(self) -> dict:
        """The index from the product files, when it is missing or unreadable."""
        seen = {}
        for f in sorted(self.dir.glob("*.md")):
            try:
                entries = parse(f.read_text(errors="replace"))
            except OSError:
                continue
            for e in entries:
                kept, cut = kept_text(e["text"])
                seen[f"{f.stem}:{digest(kept)}"] = {
                    "product": f.stem, "date": e["date"][:10], "session": e["session"],
                    "harness": e["harness"], "chars": len(kept) + cut}
        return seen

    def _write_index(self) -> None:
        from . import config
        tmp = self.dir / f"{INDEX_NAME}.{os.getpid()}.tmp"
        config.write_private(tmp, json.dumps({"version": INDEX_VERSION, "seen": self.index}, ensure_ascii=False, sort_keys=True))
        os.replace(tmp, self.dir / INDEX_NAME)
        self._dirty = False

    # write ---------------------------------------------------------------------------------
    def has(self, product: str, text: str) -> bool:
        return f"{product}:{digest(text)}" in self.index

    def add(self, product: str, text: str, harness: str, session: str, when: _dt.datetime) -> bool:
        """Append one entry unless this product already has the same text. `text` is stored
        scrubbed. True when it was (or, in a dry store, would be) written."""
        key, entry, row = render(product, text, harness, session, when)
        if key in self.index or key in self._planned:
            return False
        if self.dry:
            self._planned.add(key)
            return True
        corrections._append_line(self.dir / f"{product}.md", entry)
        self.index[key] = row
        self._dirty = True
        return True


def render(product: str, text: str, harness: str, session: str, when: _dt.datetime) -> tuple[str, str, dict]:
    """(dedupe key, the entry as written to the file, its index row) for one prompt, scrubbed."""
    text = corrections.scrub(text.strip())
    body = text
    if len(body) > MAX_CHARS:
        body = body[:MAX_CHARS] + f"\n[{len(text) - MAX_CHARS} more characters not kept]"
    when = when.astimezone() if when.tzinfo else when
    head = f"## {when.strftime('%Y-%m-%d %H:%M')} · {_word(harness)} · session {_word(session)[:8]}"
    row = {"product": product, "date": when.strftime("%Y-%m-%d"), "session": _word(session)[:8],
           "harness": _word(harness), "chars": len(text)}
    return f"{product}:{digest(text)}", f"{head}\n{_escape(body)}\n\n", row


def _word(s) -> str:
    return re.sub(r"\s+", "", str(s or "")) or "unknown"


# --- read ---------------------------------------------------------------------------------

def products() -> list[dict]:
    """[{product, entries, latest, path}] for every product file, by name."""
    out = []
    d = intent_dir()
    for f in sorted(d.glob("*.md")) if d.is_dir() else []:
        es = parse(_read(f))
        out.append({"product": f.stem, "entries": len(es), "latest": max((e["date"] for e in es), default=""),
                    "path": str(f)})
    return out


def _read(f: pathlib.Path) -> str:
    try:
        return f.read_text(errors="replace")
    except OSError:
        return ""


def entries(product: str) -> list[dict]:
    """The entries of `product`, oldest first."""
    es = parse(_read(intent_dir() / f"{_clean_name(product)}.md"))
    for e in es:
        e["product"] = product
        e["chars"] = len(e["text"])
    return sorted(es, key=lambda e: e["date"])


def resolve(name: str) -> str | None:
    """The product file stem `name` names: itself, `.` for the cwd's product, or the one file
    that matches it ignoring case."""
    if name == ".":
        name = product_for(os.getcwd())
    name = _clean_name(name)
    have = [p["product"] for p in products()]
    if name in have:
        return name
    low = [h for h in have if h.lower() == name.lower()]
    return low[0] if len(low) == 1 else None


# --- the capture hook ---------------------------------------------------------------------

_SESSION_KEYS = ("session_id", "sessionId", "conversation_id", "conversationId", "thread_id")


def _session_of(d: dict) -> str:
    for k in _SESSION_KEYS:
        v = d.get(k)
        if isinstance(v, str) and v:
            return v
    ex = d.get("extra")
    return _session_of(ex) if isinstance(ex, dict) else ""


def guess_harness(data: dict, env=None) -> str:
    env = os.environ if env is None else env
    tp = str(data.get("transcript_path") or "")
    if "/.codex/" in tp:
        return "codex"
    if "/.claude/" in tp or env.get("CLAUDE_PROJECT_DIR") or env.get("CLAUDE_PLUGIN_ROOT"):
        return "claude"
    if isinstance(data.get("extra"), dict) or any(k.startswith("HERMES_") for k in env):
        return "hermes"
    return "other"


def capture(data: dict, now: _dt.datetime | None = None, cfg: dict | None = None,
            harness: str | None = None) -> bool:
    """What the UserPromptSubmit hook does with one payload. True when an entry was written."""
    if not isinstance(data, dict):
        return False
    enabled, min_chars = settings(cfg)
    if not enabled:
        return False
    prompt = corrections._pick(data)
    if not isinstance(prompt, str) or corrections.headless(data):
        return False
    text = typed(prompt)
    raw = _bare(prompt)
    if raw and len(raw) <= ANSWER_MAX and data.get("transcript_path"):
        # a button label such as "Continue" reads as a retry to `typed`; match it before that test
        text = _as_answer(raw, pending_ask(str(data["transcript_path"])), text)
    if not text or not long_enough(text, min_chars):
        return False
    cwd = data.get("cwd") or data.get("workspaceRoot") or data.get("workspace_root") or os.getcwd()
    now = now or _dt.datetime.now(_dt.timezone.utc)
    with Store() as st:
        return st.add(product_for(cwd), text, harness or guess_harness(data), _session_of(data), now)


def hook_main(stream=None, harness: str | None = None) -> None:
    """Entry point for plugin/hooks/capture-intent.sh. Never raises, never prints:
    UserPromptSubmit stdout is injected into the model's context."""
    try:
        capture(json.load(stream or sys.stdin), harness=harness)
    except BaseException:  # noqa: BLE001 — a hook must never fail the session
        pass


# --- backfill -----------------------------------------------------------------------------

_HARNESS_LABEL = {"claude-code": "claude", "codex": "codex"}


ANSWER_MAX = 200          # a reply longer than this is a prompt of its own, not a button press
ASK_TAIL_BYTES = 512_000  # how much of a transcript's end the live hook reads to find the open question


def _ask_of(o: dict) -> tuple[str, list[str]] | None:
    """(question, button labels) when an assistant record opens a next-step box: the desktop
    app's `wrap_up` call with an `ask` and buttons. The label of the button pressed comes back
    as the next user turn."""
    if o.get("type") != "assistant":
        return None
    for b in (o.get("message") or {}).get("content") or []:
        if not (isinstance(b, dict) and b.get("type") == "tool_use" and str(b.get("name", "")).endswith("wrap_up")):
            continue
        inp = b.get("input") if isinstance(b.get("input"), dict) else {}
        acts = inp.get("actions")
        if isinstance(acts, str):
            try:
                acts = json.loads(acts)
            except ValueError:
                acts = []
        labels = [a["label"] for a in acts or [] if isinstance(a, dict) and isinstance(a.get("label"), str)]
        if isinstance(inp.get("ask"), str) and inp["ask"].strip() and labels:
            return inp["ask"].strip(), labels
    return None


def _label_key(s: str) -> str:
    return " ".join(s.split()).strip(" .!").casefold()


def _bare(text) -> str:
    """A user turn without its system reminders and images, before any other test."""
    from .adapters import strip_reminders
    return strip_reminders(_IMAGE_TAG_RE.sub("", text if isinstance(text, str) else "")).strip()


def _as_answer(raw: str, ask: tuple[str, list[str]] | None, otherwise: str | None) -> str | None:
    """`raw` as an answer to `ask` when it is one of its button labels, else `otherwise`."""
    if ask and raw and _label_key(raw) in {_label_key(l) for l in ask[1]}:
        return answer_text([(ask[0], raw)]) or otherwise
    return otherwise


def _raw_turn(o: dict) -> str | None:
    """The raw text of a user record a person could have typed (a prompt, or a prompt queued while
    the agent worked), or None. Tool results, meta turns, compaction summaries and sidechains are not."""
    from .adapters import text_of
    if o.get("isSidechain"):
        return None
    if o.get("type") == "attachment":
        a = o.get("attachment") or {}
        origin = a.get("origin") if isinstance(a.get("origin"), dict) else {}
        if a.get("type") != "queued_command" or a.get("commandMode") != "prompt" or origin.get("kind", "human") != "human":
            return None
        return text_of(a.get("prompt"))
    if o.get("type") != "user" or o.get("isMeta") or o.get("isCompactSummary"):
        return None
    c = (o.get("message") or {}).get("content")
    if isinstance(c, list) and any(isinstance(b, dict) and b.get("type") == "tool_result" for b in c):
        return None
    return text_of(c)


def _human_turn(o: dict) -> str | None:
    """What a person typed in a record, under the text rules, or None."""
    raw = _raw_turn(o)
    return typed(raw.strip()) if raw else None


def _question_answers(o: dict) -> str | None:
    """The answers to an AskUserQuestion call, each with its question and any note typed with it."""
    r = o.get("toolUseResult")
    if o.get("type") != "user" or o.get("isSidechain") or not isinstance(r, dict) or not isinstance(r.get("answers"), dict):
        return None
    notes = r.get("annotations") if isinstance(r.get("annotations"), dict) else {}
    pairs = []
    for q, a in r["answers"].items():
        n = notes.get(q, {}).get("notes") if isinstance(notes.get(q), dict) else None
        pairs.append((q, f"{a}\n{n.strip()}" if isinstance(n, str) and n.strip() else a))
    return answer_text(pairs)


def pending_ask(path: str) -> tuple[str, list[str]] | None:
    """The question of the last next-step box in a Claude Code transcript, if nobody has typed
    since. The live hook runs before the prompt it sees is written to the transcript."""
    from .adapters import iter_jsonl
    ask = None
    try:
        for o in iter_jsonl(path, tail_bytes=ASK_TAIL_BYTES):
            if not isinstance(o, dict):
                continue
            a = _ask_of(o)
            if a:
                ask = a
            elif _bare(_raw_turn(o)):
                ask = None
    except (OSError, ValueError):
        return None
    return ask


def _claude_prompts(path: str):
    """(ts, cwd, text) for each thing a person said in a Claude Code transcript, full length: a
    prompt, a prompt queued while the agent worked, a button pressed or an AskUserQuestion
    answered (each with its question). A prompt after a compaction is a prompt like any other."""
    ask = None
    for o in _jsonl(path):
        a = _ask_of(o)
        if a:
            ask = a
            continue
        t = _question_answers(o)
        if t:
            yield o.get("timestamp"), o.get("cwd"), t
            continue
        raw = _raw_turn(o)
        if not raw:
            continue
        t = typed(raw.strip())
        bare = _bare(raw)
        if ask and bare and len(bare) <= ANSWER_MAX:
            t = _as_answer(bare, ask, t)
        if not t:
            continue
        ask = None
        ts = (o.get("attachment") or {}).get("timestamp") if o.get("type") == "attachment" else None
        yield ts or o.get("timestamp"), o.get("cwd"), t


def _codex_prompts(path: str):
    from .adapters import codex
    for o in _jsonl(path):
        p = o.get("payload")
        if o.get("type") != "response_item" or not isinstance(p, dict) or p.get("type") != "message" or p.get("role") != "user":
            continue
        raw = codex._text_of(p.get("content")).strip()
        t = typed(codex.strip_injected(raw)) if raw else None
        if t:
            yield o.get("timestamp"), None, t


def _jsonl(path: str):
    try:
        with open(path, errors="replace") as fh:
            for line in fh:
                try:
                    o = json.loads(line)
                except ValueError:
                    continue
                if isinstance(o, dict):
                    yield o
    except OSError:
        return


def _when(ts) -> _dt.datetime | None:
    try:
        d = _dt.datetime.fromisoformat(str(ts).replace("Z", "+00:00"))
    except ValueError:
        return None
    return d if d.tzinfo else d.replace(tzinfo=_dt.timezone.utc)


def backfill(days: int = 30, dry: bool = False, cfg: dict | None = None, roots: dict | None = None) -> dict:
    """Capture the long human prompts of the last `days` days from the Claude Code and Codex
    transcripts. {product: {"found": n, "new": n}}; `new` is what was written (or would be, with
    `dry`)."""
    from .adapters import claude_code, codex, since_epoch
    enabled, min_chars = settings(cfg)
    if not enabled:
        return {}
    cutoff = _dt.datetime.now(_dt.timezone.utc) - _dt.timedelta(days=days)
    found: list[tuple[_dt.datetime, str, str, str, str]] = []
    sessions = []
    for mod in (claude_code, codex):  # the two adapters that keep whole prompts on disk
        try:
            sessions += mod.load(since=since_epoch(days), **(roots or {}).get(mod.NAME, {}))
        except FileNotFoundError:
            continue
    for s in sessions:
        if s.batch or s.sidechain:
            continue
        gen = _claude_prompts(s.path) if s.harness == "claude-code" else _codex_prompts(s.path)
        for ts, cwd, text in gen:
            when = _when(ts)
            if when is None or when < cutoff or not long_enough(text, min_chars):
                continue
            where = cwd or s.cwd
            found.append((when, product_for(where) if where else "misc", _HARNESS_LABEL[s.harness], s.sid, text))
    found.sort(key=lambda r: r[0])
    out: dict[str, dict] = {}
    if not found:
        return out
    with Store(wait_s=30.0, dry=dry) as st:
        for when, product, harness, sid, text in found:
            row = out.setdefault(product, {"found": 0, "new": 0})
            row["found"] += 1
            if st.add(product, text, harness, sid, when):
                row["new"] += 1
    return out


# --- clean --------------------------------------------------------------------------------

def not_owners(e: dict) -> str | None:
    """Why a stored entry (as `parse` returns it) is not the owner's own words under today's
    rules, or None when it is. The rules are the ones the hook applies, as far as a stored entry
    lets them be checked: the text tests, and for Grok the session store's headless flag."""
    from .adapters import is_noise_turn
    kept, _ = kept_text(e["text"])
    t = kept.lstrip()
    if automated(t) or is_noise_turn(t):
        return "automated"
    if t.startswith("<user_query>"):
        return "headless envelope"
    if e["harness"] == "grok" and corrections.grok_headless(e["session"]) is True:
        return "grok -p"
    return None


def _segments(raw: str) -> list[tuple[dict | None, str]]:
    """A product file as (parsed entry or None, its exact text): the lines before the first header
    come first with None. The texts joined are `raw`, byte for byte."""
    lines = raw.split("\n")
    heads = [i for i, l in enumerate(lines) if HEADER_RE.match(l)]
    cuts = ([0] if not heads or heads[0] else []) + heads + [len(lines)]
    out = []
    for a, b in zip(cuts, cuts[1:]):
        text = "\n".join(lines[a:b]) + ("\n" if b < len(lines) else "")
        m = HEADER_RE.match(lines[a])
        if not m:
            out.append((None, text))
            continue
        body = _unescape("\n".join(lines[a + 1:b]).strip("\n"))
        out.append(({"date": m.group(1), "harness": m.group(2), "session": m.group(3), "text": body}, text))
    return out


def _write_new(path: pathlib.Path, data: bytes) -> None:
    """A new 0600 file, fsynced; fails if `path` exists."""
    from . import config
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600)
    try:
        config.write_all(fd, data)
        os.fsync(fd)
    finally:
        os.close(fd)


def _replace(f: pathlib.Path, raw: str, new: str, stamp: str) -> pathlib.Path:
    """Copy `f` (whose text is `raw`) to `<file>.bak-<stamp>`, then replace it with `new`
    atomically. The caller holds the store lock. The backup's path."""
    bak, n = f.with_name(f"{f.name}.bak-{stamp}"), 1
    while True:
        try:
            _write_new(bak, raw.encode("utf-8", "surrogateescape"))
            break
        except FileExistsError:
            n += 1
            bak = f.with_name(f"{f.name}.bak-{stamp}-{n}")
    tmp = f.with_name(f"{f.name}.{os.getpid()}.tmp")
    try:
        _write_new(tmp, new.encode("utf-8", "surrogateescape"))
        os.replace(tmp, f)
    finally:
        with contextlib.suppress(OSError):
            tmp.unlink()
    return bak


def clean(dry: bool = False, now: _dt.datetime | None = None) -> list[dict]:
    """Remove the stored entries `not_owners` names. [{product, date, harness, session, text,
    why}] for what was removed (or, with `dry`, would be). Each changed file is first copied to
    `<file>.bak-<UTC time>`; then file and index are replaced atomically, under the store lock."""
    now = now or _dt.datetime.now(_dt.timezone.utc)
    stamp = now.astimezone(_dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out: list[dict] = []
    if not intent_dir().is_dir():
        return out
    with Store(wait_s=30.0, dry=dry) as st:
        for f in sorted(st.dir.glob("*.md")):
            try:
                raw = f.read_bytes().decode("utf-8", "surrogateescape")
            except OSError:
                continue
            keep, dropped = [], []
            for e, text in _segments(raw):
                why = not_owners(e) if e else None
                if why:
                    dropped.append((e, why))
                else:
                    keep.append(text)
            if not dropped:
                continue
            for e, why in dropped:
                out.append({"product": f.stem, "date": e["date"], "harness": e["harness"], "session": e["session"],
                            "text": e["text"], "why": why})
            if dry:
                continue
            _replace(f, raw, "".join(keep), stamp)
            for e, _ in dropped:
                kept, _cut = kept_text(e["text"])
                st.index.pop(f"{f.stem}:{digest(kept)}", None)
            st._dirty = True
    return out


# --- rebuild ------------------------------------------------------------------------------

SCAN_MARGIN = _dt.timedelta(minutes=5)

def rebuild(product: str, days: int | None = None, dry: bool = False, now: _dt.datetime | None = None,
            cfg: dict | None = None, roots: dict | None = None) -> dict:
    """One product's file made again from the Claude Code and Codex transcripts under today's
    rules, for entries stored under older ones (an agent's message kept as the owner's words, an
    answer kept without its question, a queued prompt missed).

    An entry whose session has a transcript is replaced by what that transcript yields now. An
    entry with no transcript (a deleted one, another harness) stays if today's text rules keep it.
    With `days`, only sessions and entries of the last `days` days are touched; older entries stay
    as they are. The old file is copied to `<file>.bak-<UTC time>` first.

    {"product", "before", "after", "added": [entry], "dropped": [entry + why], "backup"}."""
    from .adapters import claude_code, codex, since_epoch
    now = now or _dt.datetime.now(_dt.timezone.utc)
    _, min_chars = settings(cfg)
    # An entry the hook wrote just before or during the scan may be missing from what was read of its
    # transcript; anything from SCAN_MARGIN before the scan on is judged by the text rules alone.
    scanned = (_dt.datetime.now(_dt.timezone.utc) - SCAN_MARGIN).astimezone().strftime("%Y-%m-%d %H:%M")
    cutoff = now - _dt.timedelta(days=days) if days else None
    floor = cutoff.astimezone().strftime("%Y-%m-%d %H:%M") if cutoff else ""
    sessions = []
    for mod in (claude_code, codex):
        try:
            sessions += mod.load(since=since_epoch(days), **(roots or {}).get(mod.NAME, {}))
        except FileNotFoundError:
            continue
    seen = {(_HARNESS_LABEL[s.harness], _word(s.sid)[:8]) for s in sessions}   # batch sessions too: never the owner's
    fresh: list[tuple[str, str, str]] = []                 # (date, key, entry text)
    for s in sessions:
        if s.batch or s.sidechain:
            continue
        gen = _claude_prompts(s.path) if s.harness == "claude-code" else _codex_prompts(s.path)
        for ts, cwd, text in gen:
            when = _when(ts)
            where = cwd or s.cwd
            if when is None or (cutoff and when < cutoff) or not long_enough(text, min_chars):
                continue
            if (product_for(where) if where else "misc") != product:
                continue
            key, entry, _row = render(product, text, _HARNESS_LABEL[s.harness], s.sid, when)
            fresh.append((entry[3:19], key, entry))
    f = intent_dir() / f"{_clean_name(product)}.md"
    stamp = now.astimezone(_dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    with Store(wait_s=30.0, dry=dry) as st:              # read, merge and write under one lock
        try:
            raw = f.read_bytes().decode("utf-8", "surrogateescape")
        except FileNotFoundError:
            raw = ""
        out, new = _merge(product, raw, fresh, seen, floor, scanned)
        if dry or (not out["added"] and not out["dropped"]):
            return out
        if f.exists():
            out["backup"] = str(_replace(f, raw, new, stamp))
        else:
            _write_new(f, new.encode("utf-8", "surrogateescape"))
        for k in [k for k in st.index if k.startswith(f"{product}:")]:
            del st.index[k]
        for e in parse(new):
            kept_t, cut = kept_text(e["text"])
            st.index[f"{product}:{digest(kept_t)}"] = {"product": product, "date": e["date"][:10], "session": e["session"],
                                                       "harness": e["harness"], "chars": len(kept_t) + cut}
        st._dirty = True
    return out


def _merge(product: str, raw: str, fresh: list[tuple[str, str, str]], seen: set[str], floor: str,
           scanned: str = "9999") -> tuple[dict, str]:
    """`rebuild`'s decision for one file: (report, the new file text). An entry written in or
    after the minute the scan began (`scanned`) may postdate what was read of its transcript, so
    only the text rules judge it."""
    def key_of(text: str) -> str:
        return f"{product}:{digest(kept_text(text)[0])}"
    lead, kept, dropped, old_keys, before = [], [], [], set(), 0
    for e, text in _segments(raw):
        if e is None:
            lead.append(text)
            continue
        before += 1
        old_keys.add(key_of(e["text"]))
        why = None
        if e["date"] >= floor:
            why = ("not in its transcript" if (e["harness"], e["session"]) in seen and e["date"] < scanned
                   else not_owners(e))
        if why:
            dropped.append(dict(e, product=product, why=why))
        else:
            kept.append((e["date"], key_of(e["text"]), text if text.endswith("\n") else text + "\n"))
    have = {k for _, k, _ in kept}
    added = []
    for date, key, entry in sorted(fresh, key=lambda r: r[0]):
        if key in have:
            continue
        have.add(key)
        kept.append((date, key, entry))
        if key not in old_keys:
            e = parse(entry)[0]
            added.append(dict(e, product=product))
    dropped = [d for d in dropped if key_of(d["text"]) not in have]   # the same words read again are not a change
    kept.sort(key=lambda r: r[0])
    return ({"product": product, "before": before, "after": len(kept), "added": added, "dropped": dropped, "backup": None},
            "".join(lead) + "".join(t for _, _, t in kept))


# --- commands -----------------------------------------------------------------------------

def _line(e: dict, product: bool = False) -> str:
    first = " ".join(e["text"].split())[:100]
    head = f"{e['product']:18} " if product else ""
    return f"{head}{e['date']}  {e['harness']:7} {e['chars']:6}  {first}"


def _list_entries(args, names: list[str]) -> list[dict]:
    from .intent_status import entry_id
    es = [dict(e, id=entry_id(e)) for n in names for e in entries(n)]
    if args.days:
        floor = (_dt.date.today() - _dt.timedelta(days=args.days)).isoformat()
        es = [e for e in es if e["date"][:10] >= floor]
    if args.grep:
        g = args.grep.lower()
        es = [e for e in es if g in e["text"].lower()]
    return sorted(es, key=lambda e: e["date"])


def cmd_intent(args) -> int:
    words = list(args.words or [])
    if words and words[0] == "list" and resolve("list") is None:
        words = words[1:]  # `teyla intent list` is the bare listing the help names (a product called "list" wins)
    sub = words[0] if words and words[0] in ("capture", "backfill", "path", "cover", "clean", "rebuild", "audit", "mark", "load") else None
    if sub in ("audit", "mark", "load"):
        from . import intent_status
        return intent_status.cmd(args, words)
    if sub == "cover":
        from . import intent_cover
        return intent_cover.cmd_cover(args, words)
    if sub == "capture":
        hook_main()
        return 0
    if sub == "backfill":
        enabled, _ = settings()
        if not enabled:
            print("intent capture is off ([intent] enabled = false); nothing done")
            return 0
        days = args.days or 30
        res = backfill(days=days, dry=args.dry)
        verb = "would add" if args.dry else "added"
        if not res:
            print(f"no long prompts found in the last {days} days")
            return 0
        for product in sorted(res):
            r = res[product]
            print(f"{product:24} found {r['found']:4}   {verb} {r['new']:4}   already kept {r['found'] - r['new']:4}")
        print(f"{'total':24} found {sum(r['found'] for r in res.values()):4}   {verb} {sum(r['new'] for r in res.values()):4}"
              f"   in {len(res)} product(s), last {days} days")
        return 0
    if sub == "clean":
        if len(words) != 1:
            print("usage: teyla intent clean [--dry]", file=sys.stderr)
            return 64
        try:
            gone = clean(dry=args.dry)
        except TimeoutError:
            print("teyla: the intent store is locked; try again in a moment", file=sys.stderr)
            return 1
        verb = "would remove" if args.dry else "removed"
        for g in gone:
            first = " ".join(g["text"].split())[:60]
            print(f"{g['product']:18} {g['date'][:10]}  {g['harness']:7} {g['session']:8}  {g['why']:17} {first}")
        n = len({g["product"] for g in gone})
        print(f"{verb} {len(gone)} entr{'y' if len(gone) == 1 else 'ies'} in {n} product(s)"
              + ("; nothing written" if args.dry else "; each changed file was copied to <file>.bak-<time> first"))
        return 0
    if sub == "rebuild":
        return _cmd_rebuild(args, words)
    if sub == "path":
        if len(words) != 2:
            print("usage: teyla intent path <product>", file=sys.stderr)
            return 64
        name = resolve(words[1])
        if name is None:
            p = intent_dir() / f"{_clean_name(product_for(os.getcwd()) if words[1] == '.' else words[1])}.md"
            print(p)
            print(f"teyla: no intent recorded for {words[1]} yet", file=sys.stderr)
            return 1
        print(intent_dir() / f"{name}.md")
        return 0
    if len(words) > 1:
        print("usage: teyla intent [product] [--days N] [--grep TEXT] [--json] | path <product> | cover <plan.md> | audit <product>"
              " | mark <id> <status> | load <product> <file.json> | backfill | clean | rebuild <product> | capture",
              file=sys.stderr)
        return 64
    if words:
        name = resolve(words[0])
        if name is None:
            print(f"teyla: no intent recorded for {words[0]}", file=sys.stderr)
            return 1
        es = _list_entries(args, [name])
        if args.json:
            print(json.dumps(es, ensure_ascii=False, indent=2))
        else:
            for e in es:
                print(_line(e))
            if not es:
                print("no entries match")
        return 0
    if args.grep or args.days:
        es = _list_entries(args, [p["product"] for p in products()])
        if args.json:
            print(json.dumps(es, ensure_ascii=False, indent=2))
        else:
            for e in es:
                print(_line(e, product=True))
            if not es:
                print("no entries match")
        return 0
    ps = products()
    if args.json:
        print(json.dumps(ps, ensure_ascii=False, indent=2))
        return 0
    if not ps:
        print("no intent recorded yet; teyla intent backfill --days 30 fills it from the transcripts")
        return 0
    for p in ps:
        print(f"{p['product']:24} {p['entries']:4} entries   latest {p['latest'][:10]}")
    return 0


def _cmd_rebuild(args, words: list[str]) -> int:
    if len(words) != 2:
        print("usage: teyla intent rebuild <product> [--days N] [--dry] [--json]", file=sys.stderr)
        return 64
    name = resolve(words[1]) or _clean_name(words[1])
    try:
        r = rebuild(name, days=args.days, dry=args.dry)
    except TimeoutError:
        print("teyla: the intent store is locked; try again in a moment", file=sys.stderr)
        return 1
    if args.json:
        print(json.dumps(r, ensure_ascii=False, indent=2))
        return 0
    for e in r["dropped"]:
        print(f"- {e['date'][:10]}  {e['harness']:7} {e['session']:8}  {e['why']:22} {' '.join(e['text'].split())[:60]}")
    for e in r["added"]:
        print(f"+ {e['date'][:10]}  {e['harness']:7} {e['session']:8}  {'':22} {' '.join(e['text'].split())[:60]}")
    window = f", last {args.days} days" if args.days else ""
    verb = ("would drop", "would add") if args.dry else ("dropped", "added")
    tail = ("; nothing written" if args.dry else f"; the old file is {r['backup']}" if r["backup"] else "; nothing to change")
    print(f"{name}: {r['before']} entries -> {r['after']}: {verb[0]} {len(r['dropped'])}, {verb[1]} {len(r['added'])}{window}{tail}")
    return 0


