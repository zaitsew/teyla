"""`teyla intent` — the owner's own long prompts, kept word for word, one file per product.

    ~/.teyla/intent/<product>.md      append-only, 0600, in a 0700 directory
    ~/.teyla/intent/.index.json       hashes, dates, product, session, length (dedupe only)

Why: the owner describes a goal in a long prompt. An agent turned it into a plan, a later
session worked from the plan, and the detail was gone: a summary had replaced the source. So
nothing here summarises. A prompt of `intent.min_chars` (default 400) or more is stored as typed,
after `corrections.scrub` has replaced secrets, and a planning session is pointed at the file.

    teyla intent                         one line per product: entries, latest date
    teyla intent <product> [--days N] [--grep TEXT] [--json]   one line per entry
    teyla intent path <product>          the file, for `cat "$(teyla intent path x)"`
    teyla intent backfill [--days 30] [--dry]   the same capture from Claude Code and Codex transcripts
    teyla intent capture                 what plugin/hooks/capture-intent.sh runs (JSON on stdin)

An entry:

    ## 2026-10-16 18:40 · claude · session 1a2b3c4d
    <the prompt, verbatim, secrets scrubbed>

Product is the repo name of the prompt's cwd. A worktree (`<repo>/.claude/worktrees/<x>`,
`~/.worktrees/<repo>/<branch>`, or any checkout whose `.git` file points at a main checkout)
maps to its repo; a cwd outside any repo goes to `general`.

What is not stored: prompts a script or another agent wrote (`claude -p`, `codex exec`, Codex
review briefs, subagent briefs, injected AGENTS.md text), harness-injected turns (system
reminders, task notifications, slash-command expansions) and images. Text pasted into a prompt
arrives inline and cannot be told from typing; a prompt over MAX_CHARS keeps its first MAX_CHARS
characters and says how many were left out. A line of a prompt that looks like an entry
header gets a backslash in front, so the file stays parseable.

Writes are safe under concurrent hooks: one flock around "read index, append, write index",
the file written with O_APPEND and fsynced, the index replaced atomically. A hook that cannot
get the lock within a second skips the capture; `teyla intent backfill` finds it again.
Everything the hook runs is stdlib.
"""
from __future__ import annotations

import contextlib
import datetime as _dt
import hashlib
import json
import os
import pathlib
import re
import sys
import time

from . import corrections

try:  # POSIX only; without it the lock is skipped and dedupe is best effort
    import fcntl
except ImportError:  # pragma: no cover
    fcntl = None

MIN_CHARS = 400
MAX_CHARS = 50_000      # a longer prompt keeps its first MAX_CHARS characters; also the length the dedupe key covers
INDEX_VERSION = 2       # 1 hashed whole prompts with every line break collapsed; an older index is rebuilt
LOCK_WAIT_S = 1.0
INDEX_NAME = ".index.json"
LOCK_NAME = ".lock"

HEADER_RE = re.compile(r"^## (\d{4}-\d\d-\d\d \d\d:\d\d) · (\S+) · session (\S*)$")
_WORKTREE_RES = (
    re.compile(r"^(?P<root>.+?)/\.claude/worktrees(?:/|$)"),   # <repo>/.claude/worktrees/<x>
    re.compile(r"/\.worktrees/(?P<name>[^/]+)(?:/|$)"),        # ~/.worktrees/<repo>/<branch>
)

# Prompts that look typed but were written by a harness, a script or another agent. Both the live hook
# and the backfill use it.
_AUTOMATED_PREFIXES = (
    "# AGENTS.md instructions",
    "<INSTRUCTIONS>",
    "Base directory for this skill:",
    "<scheduled-task",
    "<artifact-content",
    "<bash-input>",
    "<bash-stdout>",
    "Caveat: The messages below were generated by the user while running local commands",
    "Codex could not read",
    "IMPORTANT: Do NOT read",
    "Background (from the session that started this one)",   # a brief one agent session wrote for another
    "You are reviewing a pull request diff",                 # codex-review / claude-review prompts
    "<task-notification",
    "<side-sessions-event",
    "<ci-monitor-event",
)
_AUTOMATED_HEAD_RE = re.compile(r"One-pass code review")
_IMAGE_TAG_RE = re.compile(r"</?image\b[^>]*>")


# --- where --------------------------------------------------------------------------------

def intent_dir() -> pathlib.Path:
    return corrections.teyla_home() / "intent"


def _clean_name(name: str) -> str:
    name = re.sub(r"[^A-Za-z0-9._-]+", "-", name or "").strip("-.")
    return name or "misc"


def product_for(cwd) -> str:
    """The product a prompt typed in `cwd` belongs to. Pure filesystem and path matching, no
    `git` subprocess (the hook runs on every prompt, and /usr/bin/git on a Mac without the
    developer tools pops a dialog). The path rules come first so a worktree that has been
    deleted since still maps to its repo."""
    try:
        p = pathlib.Path(cwd).expanduser().resolve()
    except (OSError, RuntimeError, TypeError, ValueError):
        return "misc"
    s = p.as_posix()
    m = _WORKTREE_RES[0].match(s)
    if m:
        return _clean_name(pathlib.PurePosixPath(m.group("root")).name)
    m = _WORKTREE_RES[1].search(s)
    if m:
        return _clean_name(m.group("name"))
    root, _ = corrections.find_repo(p)
    # Outside any repo (a parent folder like ~/repos, a download folder, a path that is gone):
    # one shared file, not a product named after whatever directory the session sat in.
    return _clean_name(root.name) if root else "general"


# --- what counts --------------------------------------------------------------------------

def automated(text: str) -> bool:
    """A prompt the owner did not type: an injected AGENTS.md, a review brief, a scheduled task,
    a skill's expansion."""
    t = (text or "").lstrip()
    return t.startswith(_AUTOMATED_PREFIXES) or bool(_AUTOMATED_HEAD_RE.search(t[:300]))


def typed(text: str | None) -> str | None:
    """What the owner typed in a user turn, or None: nothing left after the harness's own
    injections, an automated prompt, a retry."""
    from .adapters import human_text
    t = _IMAGE_TAG_RE.sub("", text or "").strip()
    t = human_text(t) if t else None
    if not t or automated(t):
        return None
    return t


def settings(cfg: dict | None = None) -> tuple[bool, int]:
    """(enabled, min_chars) from `[intent]`; a broken config means the defaults."""
    try:
        if cfg is None:
            from . import config
            cfg = config.load(corrections.teyla_home() / "config.toml")
        sec = (cfg or {}).get("intent") or {}
        enabled = sec.get("enabled", True)
        enabled = enabled if isinstance(enabled, bool) else str(enabled).strip().lower() not in ("0", "false", "no", "off")
        n = int(sec.get("min_chars", MIN_CHARS))
        return enabled, max(1, n)
    except Exception:  # noqa: BLE001 — a broken config must not stop a capture
        return True, MIN_CHARS


_CUT_RE = re.compile(r"\n\[(\d+) more characters not kept\]$")


def normalise(text: str) -> str:
    """The dedupe form: spaces within a line collapse, line ends and the blank lines around the
    text are ignored, but the line breaks stay. Two prompts that differ only in their layout are
    two prompts."""
    lines = (text or "").replace("\r\n", "\n").replace("\r", "\n").split("\n")
    return "\n".join(" ".join(l.split()) for l in lines).strip("\n")


def digest(text: str) -> str:
    """The dedupe key. It covers the first MAX_CHARS characters only, which is all an entry keeps,
    so a cut entry read back from the file has the key its full text had when it was written."""
    return hashlib.sha256(normalise(text[:MAX_CHARS]).encode("utf-8", "surrogatepass")).hexdigest()[:16]


def kept_text(text: str) -> tuple[str, int]:
    """(the prompt as kept, characters left out) for an entry's text: the closing
    `[N more characters not kept]` line of a cut entry is not part of the owner's words."""
    m = _CUT_RE.search(text or "")
    return (text[:m.start()], int(m.group(1))) if m else (text or "", 0)


# --- the store ----------------------------------------------------------------------------

def _escape(body: str) -> str:
    """A body line that would read as an entry header gets a backslash."""
    return "\n".join("\\" + l if HEADER_RE.match(l) else l for l in body.split("\n"))


def _unescape(body: str) -> str:
    return "\n".join(l[1:] if l.startswith("\\") and HEADER_RE.match(l[1:]) else l for l in body.split("\n"))


def parse(text: str) -> list[dict]:
    """The entries of one product file: {date, harness, session, text}."""
    out, cur = [], None
    for line in text.split("\n"):
        m = HEADER_RE.match(line)
        if m:
            cur = {"date": m.group(1), "harness": m.group(2), "session": m.group(3), "lines": []}
            out.append(cur)
        elif cur is not None:
            cur["lines"].append(line)
    for e in out:
        e["text"] = _unescape("\n".join(e.pop("lines")).strip("\n"))
    return out


class Store:
    """The intent directory, locked. `with Store() as st: st.add(...)`; the index is written
    once, on exit."""

    def __init__(self, wait_s: float = LOCK_WAIT_S, dry: bool = False):
        self.dir = intent_dir()
        self.wait_s = wait_s
        self.dry = dry  # read-only: no directory made, no lock, nothing written
        self._fd = None
        self._dirty = False
        self._planned: set[str] = set()
        self.index: dict = {}

    def __enter__(self) -> "Store":
        if self.dry:
            self.index = self._load_index()
            return self
        from . import config
        config.private_dir(corrections.teyla_home())
        config.private_dir(self.dir)
        if fcntl is not None:
            self._fd = os.open(self.dir / LOCK_NAME, os.O_RDWR | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0), 0o600)
            deadline = time.monotonic() + self.wait_s
            while True:
                try:
                    fcntl.flock(self._fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
                    break
                except OSError:
                    if time.monotonic() >= deadline:
                        os.close(self._fd)
                        self._fd = None
                        raise TimeoutError("intent store is locked")
                    time.sleep(0.02)
        try:
            self.index = self._load_index()
        except BaseException:
            self._release()
            raise
        return self

    def __exit__(self, *exc) -> None:
        try:
            if self._dirty and not self.dry:
                self._write_index()  # entries already appended must stay deduped, even on an error
        finally:
            self._release()

    def _release(self) -> None:
        if self._fd is not None:
            try:
                fcntl.flock(self._fd, fcntl.LOCK_UN)
            finally:
                os.close(self._fd)
                self._fd = None

    # index ---------------------------------------------------------------------------------
    def _load_index(self) -> dict:
        p = self.dir / INDEX_NAME
        try:
            data = json.loads(p.read_text())
            seen = data["seen"]
            if isinstance(seen, dict) and data.get("version") == INDEX_VERSION:
                return seen
        except FileNotFoundError:
            if not any(self.dir.glob("*.md")):
                return {}
        except (OSError, ValueError, KeyError, TypeError):
            pass
        self._dirty = True
        return self._rebuild()

    def _rebuild(self) -> dict:
        """The index from the product files, when it is missing or unreadable."""
        seen = {}
        for f in sorted(self.dir.glob("*.md")):
            try:
                entries = parse(f.read_text(errors="replace"))
            except OSError:
                continue
            for e in entries:
                kept, cut = kept_text(e["text"])
                seen[f"{f.stem}:{digest(kept)}"] = {
                    "product": f.stem, "date": e["date"][:10], "session": e["session"],
                    "harness": e["harness"], "chars": len(kept) + cut}
        return seen

    def _write_index(self) -> None:
        from . import config
        tmp = self.dir / f"{INDEX_NAME}.{os.getpid()}.tmp"
        config.write_private(tmp, json.dumps({"version": INDEX_VERSION, "seen": self.index}, ensure_ascii=False, sort_keys=True))
        os.replace(tmp, self.dir / INDEX_NAME)
        self._dirty = False

    # write ---------------------------------------------------------------------------------
    def has(self, product: str, text: str) -> bool:
        return f"{product}:{digest(text)}" in self.index

    def add(self, product: str, text: str, harness: str, session: str, when: _dt.datetime) -> bool:
        """Append one entry unless this product already has the same text. `text` is stored
        scrubbed. True when it was (or, in a dry store, would be) written."""
        text = corrections.scrub(text.strip())
        key = f"{product}:{digest(text)}"
        if key in self.index or key in self._planned:
            return False
        if self.dry:
            self._planned.add(key)
            return True
        body = text
        if len(body) > MAX_CHARS:
            body = body[:MAX_CHARS] + f"\n[{len(text) - MAX_CHARS} more characters not kept]"
        when = when.astimezone() if when.tzinfo else when
        head = f"## {when.strftime('%Y-%m-%d %H:%M')} · {_word(harness)} · session {_word(session)[:8]}"
        corrections._append_line(self.dir / f"{product}.md", f"{head}\n{_escape(body)}\n\n")
        self.index[key] = {"product": product, "date": when.strftime("%Y-%m-%d"), "session": _word(session)[:8],
                           "harness": _word(harness), "chars": len(text)}
        self._dirty = True
        return True


def _word(s) -> str:
    return re.sub(r"\s+", "", str(s or "")) or "unknown"


# --- read ---------------------------------------------------------------------------------

def products() -> list[dict]:
    """[{product, entries, latest, path}] for every product file, by name."""
    out = []
    d = intent_dir()
    for f in sorted(d.glob("*.md")) if d.is_dir() else []:
        es = parse(_read(f))
        out.append({"product": f.stem, "entries": len(es), "latest": max((e["date"] for e in es), default=""),
                    "path": str(f)})
    return out


def _read(f: pathlib.Path) -> str:
    try:
        return f.read_text(errors="replace")
    except OSError:
        return ""


def entries(product: str) -> list[dict]:
    """The entries of `product`, oldest first."""
    es = parse(_read(intent_dir() / f"{_clean_name(product)}.md"))
    for e in es:
        e["product"] = product
        e["chars"] = len(e["text"])
    return sorted(es, key=lambda e: e["date"])


def resolve(name: str) -> str | None:
    """The product file stem `name` names: itself, `.` for the cwd's product, or the one file
    that matches it ignoring case."""
    if name == ".":
        name = product_for(os.getcwd())
    name = _clean_name(name)
    have = [p["product"] for p in products()]
    if name in have:
        return name
    low = [h for h in have if h.lower() == name.lower()]
    return low[0] if len(low) == 1 else None


# --- the capture hook ---------------------------------------------------------------------

_SESSION_KEYS = ("session_id", "sessionId", "conversation_id", "conversationId", "thread_id")


def _session_of(d: dict) -> str:
    for k in _SESSION_KEYS:
        v = d.get(k)
        if isinstance(v, str) and v:
            return v
    ex = d.get("extra")
    return _session_of(ex) if isinstance(ex, dict) else ""


def guess_harness(data: dict, env=None) -> str:
    env = os.environ if env is None else env
    tp = str(data.get("transcript_path") or "")
    if "/.codex/" in tp:
        return "codex"
    if "/.claude/" in tp or env.get("CLAUDE_PROJECT_DIR") or env.get("CLAUDE_PLUGIN_ROOT"):
        return "claude"
    if isinstance(data.get("extra"), dict) or any(k.startswith("HERMES_") for k in env):
        return "hermes"
    return "other"


def capture(data: dict, now: _dt.datetime | None = None, cfg: dict | None = None,
            harness: str | None = None) -> bool:
    """What the UserPromptSubmit hook does with one payload. True when an entry was written."""
    if not isinstance(data, dict):
        return False
    enabled, min_chars = settings(cfg)
    if not enabled:
        return False
    prompt = corrections._pick(data)
    if not isinstance(prompt, str) or corrections.headless(data):
        return False
    text = typed(prompt)
    if not text or len(text) < min_chars:
        return False
    cwd = data.get("cwd") or data.get("workspaceRoot") or data.get("workspace_root") or os.getcwd()
    now = now or _dt.datetime.now(_dt.timezone.utc)
    with Store() as st:
        return st.add(product_for(cwd), text, harness or guess_harness(data), _session_of(data), now)


def hook_main(stream=None, harness: str | None = None) -> None:
    """Entry point for plugin/hooks/capture-intent.sh. Never raises, never prints:
    UserPromptSubmit stdout is injected into the model's context."""
    try:
        capture(json.load(stream or sys.stdin), harness=harness)
    except BaseException:  # noqa: BLE001 — a hook must never fail the session
        pass


# --- backfill -----------------------------------------------------------------------------

_HARNESS_LABEL = {"claude-code": "claude", "codex": "codex"}


def _claude_prompts(path: str):
    """(ts, cwd, text) for each human turn of a Claude Code transcript, full length."""
    from .adapters import text_of
    for o in _jsonl(path):
        if o.get("type") != "user" or o.get("isMeta") or o.get("isSidechain") or o.get("isCompactSummary"):
            continue
        c = (o.get("message") or {}).get("content")
        if isinstance(c, list) and any(isinstance(b, dict) and b.get("type") == "tool_result" for b in c):
            continue
        t = typed(text_of(c).strip())
        if t:
            yield o.get("timestamp"), o.get("cwd"), t


def _codex_prompts(path: str):
    from .adapters import codex
    for o in _jsonl(path):
        p = o.get("payload")
        if o.get("type") != "response_item" or not isinstance(p, dict) or p.get("type") != "message" or p.get("role") != "user":
            continue
        raw = codex._text_of(p.get("content")).strip()
        t = typed(codex.strip_injected(raw)) if raw else None
        if t:
            yield o.get("timestamp"), None, t


def _jsonl(path: str):
    try:
        with open(path, errors="replace") as fh:
            for line in fh:
                try:
                    o = json.loads(line)
                except ValueError:
                    continue
                if isinstance(o, dict):
                    yield o
    except OSError:
        return


def _when(ts) -> _dt.datetime | None:
    try:
        d = _dt.datetime.fromisoformat(str(ts).replace("Z", "+00:00"))
    except ValueError:
        return None
    return d if d.tzinfo else d.replace(tzinfo=_dt.timezone.utc)


def backfill(days: int = 30, dry: bool = False, cfg: dict | None = None, roots: dict | None = None) -> dict:
    """Capture the long human prompts of the last `days` days from the Claude Code and Codex
    transcripts. {product: {"found": n, "new": n}}; `new` is what was written (or would be, with
    `dry`)."""
    from .adapters import claude_code, codex, since_epoch
    enabled, min_chars = settings(cfg)
    if not enabled:
        return {}
    cutoff = _dt.datetime.now(_dt.timezone.utc) - _dt.timedelta(days=days)
    found: list[tuple[_dt.datetime, str, str, str, str]] = []
    sessions = []
    for mod in (claude_code, codex):  # the two adapters that keep whole prompts on disk
        try:
            sessions += mod.load(since=since_epoch(days), **(roots or {}).get(mod.NAME, {}))
        except FileNotFoundError:
            continue
    for s in sessions:
        if s.batch or s.sidechain:
            continue
        gen = _claude_prompts(s.path) if s.harness == "claude-code" else _codex_prompts(s.path)
        for ts, cwd, text in gen:
            when = _when(ts)
            if when is None or when < cutoff or len(text) < min_chars:
                continue
            where = cwd or s.cwd
            found.append((when, product_for(where) if where else "misc", _HARNESS_LABEL[s.harness], s.sid, text))
    found.sort(key=lambda r: r[0])
    out: dict[str, dict] = {}
    if not found:
        return out
    with Store(wait_s=30.0, dry=dry) as st:
        for when, product, harness, sid, text in found:
            row = out.setdefault(product, {"found": 0, "new": 0})
            row["found"] += 1
            if st.add(product, text, harness, sid, when):
                row["new"] += 1
    return out


# --- commands -----------------------------------------------------------------------------

def _line(e: dict, product: bool = False) -> str:
    first = " ".join(e["text"].split())[:100]
    head = f"{e['product']:18} " if product else ""
    return f"{head}{e['date']}  {e['harness']:7} {e['chars']:6}  {first}"


def _list_entries(args, names: list[str]) -> list[dict]:
    es = [e for n in names for e in entries(n)]
    if args.days:
        floor = (_dt.date.today() - _dt.timedelta(days=args.days)).isoformat()
        es = [e for e in es if e["date"][:10] >= floor]
    if args.grep:
        g = args.grep.lower()
        es = [e for e in es if g in e["text"].lower()]
    return sorted(es, key=lambda e: e["date"])


def cmd_intent(args) -> int:
    words = list(args.words or [])
    sub = words[0] if words and words[0] in ("capture", "backfill", "path") else None
    if sub == "capture":
        hook_main()
        return 0
    if sub == "backfill":
        enabled, _ = settings()
        if not enabled:
            print("intent capture is off ([intent] enabled = false); nothing done")
            return 0
        days = args.days or 30
        res = backfill(days=days, dry=args.dry)
        verb = "would add" if args.dry else "added"
        if not res:
            print(f"no long prompts found in the last {days} days")
            return 0
        for product in sorted(res):
            r = res[product]
            print(f"{product:24} found {r['found']:4}   {verb} {r['new']:4}   already kept {r['found'] - r['new']:4}")
        print(f"{'total':24} found {sum(r['found'] for r in res.values()):4}   {verb} {sum(r['new'] for r in res.values()):4}"
              f"   in {len(res)} product(s), last {days} days")
        return 0
    if sub == "path":
        if len(words) != 2:
            print("usage: teyla intent path <product>", file=sys.stderr)
            return 64
        name = resolve(words[1])
        if name is None:
            p = intent_dir() / f"{_clean_name(product_for(os.getcwd()) if words[1] == '.' else words[1])}.md"
            print(p)
            print(f"teyla: no intent recorded for {words[1]} yet", file=sys.stderr)
            return 1
        print(intent_dir() / f"{name}.md")
        return 0
    if len(words) > 1:
        print("usage: teyla intent [product] [--days N] [--grep TEXT] [--json] | path <product> | backfill | capture",
              file=sys.stderr)
        return 64
    if words:
        name = resolve(words[0])
        if name is None:
            print(f"teyla: no intent recorded for {words[0]}", file=sys.stderr)
            return 1
        es = _list_entries(args, [name])
        if args.json:
            print(json.dumps(es, ensure_ascii=False, indent=2))
        else:
            for e in es:
                print(_line(e))
            if not es:
                print("no entries match")
        return 0
    if args.grep or args.days:
        es = _list_entries(args, [p["product"] for p in products()])
        if args.json:
            print(json.dumps(es, ensure_ascii=False, indent=2))
        else:
            for e in es:
                print(_line(e, product=True))
            if not es:
                print("no entries match")
        return 0
    ps = products()
    if args.json:
        print(json.dumps(ps, ensure_ascii=False, indent=2))
        return 0
    if not ps:
        print("no intent recorded yet; teyla intent backfill --days 30 fills it from the transcripts")
        return 0
    for p in ps:
        print(f"{p['product']:24} {p['entries']:4} entries   latest {p['latest'][:10]}")
    return 0


def register(sp):
    q = sp.add_parser("intent", help="the owner's long prompts, verbatim, per product: list, path, backfill")
    q.set_defaults(fn=cmd_intent)
    q.add_argument("words", nargs="*", metavar="[product|path <product>|backfill|capture]")
    q.add_argument("--days", type=int, help="list: only the last N days; backfill: the window (default 30)")
    q.add_argument("--grep", help="list: only entries containing TEXT (case-insensitive)")
    q.add_argument("--json", action="store_true", help="list: JSON, the full text of each entry")
    q.add_argument("--dry", action="store_true", help="backfill: count, write nothing")
    return q
