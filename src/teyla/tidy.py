"""`teyla tidy` — find the junk that piles up in governance markdown, and fix only the safe part.

The files: the owner's global rules (`~/.agents/POLICY.md`, `~/.claude/CLAUDE.md`), the shared
memory (`~/.claude/projects/*/memory/*.md` and each `MEMORY.md` index), and per repo `CLAUDE.md`,
`AGENTS.md` and `.claude/rules/*.md`. They grow dated anecdotes, copies of each other's lines and
pointers to files that moved. Teyla finds that deterministically (no model) and never rewrites
prose a person wrote: the editorial pass (shorten, merge, move) is the `tidy` skill, which proposes
a diff and asks.

    teyla tidy [paths...] [--json] [--quiet]     read-only report, file:line + a fix for each finding
    teyla tidy [paths...] --apply                the mechanical fixes only, backup first

Findings (rule id: what):
    dup-line         exact duplicate line or bullet (whitespace ignored) in a file; across POLICY.md and CLAUDE.md
    near-dup         bullets >= 40 chars with difflib ratio >= 0.9
    broken-import    `@path` import whose file is missing
    broken-link      markdown link to a local file that is missing
    broken-memory-link  `[[name]]` in a memory file with no such memory
    memory-index     MEMORY.md line pointing at a missing file
    memory-unlisted  memory file that MEMORY.md does not list
    memory-frontmatter  memory file without name, description or type
    size             file over `tidy.max_kb` (default 24); MEMORY.md index line over 200 chars
    trailing-ws, blank-run, tab-list   whitespace
    non-english      Cyrillic prose in a file inside a git repo (everything in a repo is English)
    stale-date       a date older than `tidy.stale_days` (default 120) on a line that says until,
                     for now, temporary, this week or TODO

Only trailing-ws, blank-run, tab-list and a dup-line whose later copy is a single bullet are
applied. Everything else is report-only.

Protected, never touched and never reported on: a fenced code block, the region between
`<!-- teyla:protect -->` and `<!-- /teyla:protect -->`, and the regions Teyla itself generates
(`teyla:cloud`, `teyla:cloud-import`, `ladder`). A fenced block whose first line holds
MERGE-APPROVED (the owner's merge-approved repo list) is one of these: it stays byte-identical
whatever its indentation, fence character or missing closing fence. After computing a fix, `apply` re-reads its own output and
refuses to write a file whose protected lines are not byte-identical to the original.

`--apply` also refuses a symlink, a file `teyla policy sync` or `harness sync` generated, a file
that changed while it ran, and any file it could not back up first
(`~/.teyla/tidy-backup/<date-time>/<flattened path>`).
"""
from __future__ import annotations

import datetime as _dt
import difflib
import json
import os
import pathlib
import re
import sys
